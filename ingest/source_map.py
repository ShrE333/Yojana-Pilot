"""State source maps: which official sites publish schemes, what kind of agency runs them.

    probe("mh")                      # check candidate domains, write sources_mh.resolved.yaml
    sources = load_sources("mh")     # resolved, usable sources
    meta_for_url(url)                # {"agency_type", "agency_name", "district"} for a scheme page

The agency type feeds the "awareness" score: district, welfare-board and corporation schemes
are the ones people rarely hear about.
"""
from __future__ import annotations

from datetime import datetime, timezone
from functools import lru_cache
from pathlib import Path

import httpx
import yaml

from .fetch import Fetcher, host_of

HERE = Path(__file__).resolve().parent
MAPS = {"mh": "sources_mh"}


def seed(code: str) -> dict:
    return yaml.safe_load((HERE / f"{MAPS[code]}.yaml").read_text(encoding="utf-8"))


def resolved_path(code: str) -> Path:
    return HERE / f"{MAPS[code]}.resolved.yaml"


def candidates(code: str) -> list[dict]:
    """Every (domain, agency) pair to probe, from the seed file."""
    s = seed(code)
    out = [{"domain": d, "name": a["name"], "agency_type": a["type"], "needs": a.get("needs", []),
            "district": None} for a in s["agencies"] for d in a["candidates"]]
    for key, info in s["districts"].items():
        names = [key] + list(info.get("aliases") or [])
        for pattern in s["district_candidates"]:
            if pattern.startswith("zp") and not info.get("zp"):
                continue
            kind = "Zilla Parishad" if pattern.startswith("zp") else "District portal"
            for n in names:
                out.append({"domain": pattern.format(d=n.replace("_", "")), "name": f"{kind} {key.title()}",
                            "agency_type": "district", "needs": [], "district": key})
    seen, unique = set(), []
    for c in out:
        if c["domain"] not in seen:
            seen.add(c["domain"])
            unique.append(c)
    return unique


def probe(code: str, fetcher: Fetcher | None = None, log=print) -> list[dict]:
    """Keep candidates whose homepage answers and whose robots.txt allows us. Writes the resolved file."""
    fetcher = fetcher or Fetcher()
    ok = []
    for c in candidates(code):
        url = f"https://{c['domain']}/"
        try:
            if not fetcher.allowed(url):
                log(f"  - {c['domain']}: robots.txt disallows or unreadable")
                continue
            r = fetcher.client.get(url)
        except httpx.HTTPError as e:
            log(f"  - {c['domain']}: {type(e).__name__}")
            continue
        if r.status_code != 200:
            log(f"  - {c['domain']}: HTTP {r.status_code}")
            continue
        final = str(r.url)
        ok.append({**c, "start_url": final, "host": host_of(final)})
        log(f"  + {c['domain']} -> {final}")
    data = {"state": seed(code)["state"], "probed_at": datetime.now(timezone.utc).isoformat(timespec="seconds"),
            "sources": ok}
    resolved_path(code).write_text(
        "# Generated by `python -m ingest --probe-sources " + code + "`. Do not edit by hand.\n"
        + yaml.safe_dump(data, allow_unicode=True, sort_keys=False), encoding="utf-8")
    load_sources.cache_clear()
    return ok


@lru_cache(maxsize=None)
def load_sources(code: str = "mh") -> tuple[dict, ...]:
    p = resolved_path(code)
    if not p.exists():
        return ()
    return tuple(yaml.safe_load(p.read_text(encoding="utf-8")).get("sources") or ())


def extra_official_domains() -> set[str]:
    out = set()
    for code in MAPS:
        out.update(seed(code).get("extra_official_domains") or [])
    return out


def scheme_link_words(code: str = "mh") -> list[str]:
    return list(seed(code)["scheme_link_words"])


def meta_for_url(url: str) -> dict:
    """Agency metadata for a page, from the resolved source maps (empty dict if unknown)."""
    host = host_of(url)
    for code in MAPS:
        for s in load_sources(code):
            if host == s["host"] or host == s["domain"] or host.endswith("." + s["domain"]):
                return {"agency_type": s["agency_type"], "agency_name": s["name"], "district": s.get("district")}
    return {}


def sources_for(profile: dict, code: str = "mh") -> list[dict]:
    """Sources worth searching for this person: their district's sites first, then state agencies."""
    district = profile.get("district")
    local = [s for s in load_sources(code) if s.get("district") and s["district"] == district]
    state = [s for s in load_sources(code) if not s.get("district")]
    return local + state
